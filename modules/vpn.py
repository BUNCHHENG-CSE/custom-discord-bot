@subcommand(
    "vpn",
    "WireGuard VPN Mesh Control Plane",
    "revoke",
    "Revoke and remove an active WireGuard tunnel",
    [
        {
            "name": "peer_id",
            "description": "Peer ID to revoke (from /vpn status)",
            "type": STR,
            "required": True,
        }
    ],
)
async def vpn_revoke(i: Interaction, peer_id: str):
    await i.defer(ephemeral=True)
    try:
        clean_id = peer_id.strip()
        await api_request(
            "DELETE",
            "/peers",
            {
                "discordUserId": str(i.user_id),
                "peerId": clean_id,
            },
        )
        await i.followup(
            f"🗑️ Successfully revoked TCT-VPN tunnel `{clean_id}`. The client key was removed from the edge gateway.",
            ephemeral=True,
        )
    except Exception as exc:
        await i.followup(f"❌ Failed to revoke tunnel: {exc}", ephemeral=True)
