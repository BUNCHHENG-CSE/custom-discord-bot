@subcommand(
    "vpn",
    "WireGuard VPN Mesh Control Plane",
    "regions",
    "List available TCT-VPN WireGuard edge gateway regions",
)
async def vpn_regions(i: Interaction):
    await i.defer(ephemeral=True)
    try:
        res = await api_request("GET", "/peers")
        nodes = res.get("nodes", [])
        if not nodes:
            return await i.followup("⚠️ No TCT-VPN edge nodes are currently online.", ephemeral=True)

        embed = {
            "title": "🌐 Available TCT-VPN Edge Regions",
            "description": "Select a region ID or code when using `/vpn create`.",
            "color": 0x10B981,  # Emerald
            "fields": [
                {
                    "name": f"{n.get('flagEmoji', '🌐')} {n.get('name', 'Gateway')} (`{n.get('id')}`)",
                    "value": (
                        f"• **Region Code:** `{n.get('region', 'N/A')}`\n"
                        f"• **Endpoint:** `{n.get('publicIp')}:{n.get('endpointPort')}`\n"
                        f"• **Peer Capacity:** `{n.get('activePeers')}/{n.get('maxPeers')}` peers\n"
                        f"• **Status:** `{n.get('status')}`"
                    ),
                    "inline": False,
                }
                for n in nodes
            ],
            "footer": {"text": "TCT-VPN High-Speed WireGuard Mesh"},
        }
        await i.followup(embeds=[embed], ephemeral=True)
    except Exception as exc:
        await i.followup(f"❌ Failed to fetch regions: {exc}", ephemeral=True)


@subcommand(
    "vpn",
    "WireGuard VPN Mesh Control Plane",
    "create",
    "Provision an instant Zero-Knowledge WireGuard VPN profile",
    [
        {
            "name": "region",
            "description": "Target region ID or code (e.g. sg1, Tokyo, or from /vpn regions)",
            "type": STR,
            "required": True,
        },
        {
            "name": "device",
            "description": "Friendly name for your device (e.g. Phone, Laptop, Gaming-Rig)",
            "type": STR,
            "required": False,
        },
    ],
)
async def vpn_create(i: Interaction, region: str, device: str = "TCT-Device"):
    await i.defer(ephemeral=True)
    try:
        clean_dev = device.strip()[:32] or "TCT-Device"
        priv_key, pub_key = generate_wireguard_keypair()

        discord_username = str(i.user.get("username") or f"discord_{i.user_id}")

        res = await api_request(
            "POST",
            "/peers",
            {
                "discordUserId": str(i.user_id),
                "discordUsername": discord_username,
                "nodeId": region.strip(),
                "deviceName": clean_dev,
                "clientPublicKey": pub_key,
            },
        )

        peer = res["peer"]
        node = res["node"]

        conf_text = build_wireguard_conf(
            device_name=peer["deviceName"],
            node_name=node["name"],
            client_private_key=priv_key,
            assigned_ip=peer["assignedIp"],
            dns_servers=node["dnsServers"],
            server_public_key=node["serverPublicKey"],
            endpoint_ip=node["publicIp"],
            endpoint_port=node["endpointPort"],
        )

        qr_bytes = render_qr_png(conf_text)
        safe_slug = re.sub(r"[^a-zA-Z0-9_-]+", "-", clean_dev.lower()).strip("-") or "device"

        embed = {
            "title": "✅ WireGuard Tunnel Provisioned",
            "description": (
                f"Your zero-knowledge encrypted tunnel is online and ready to connect.\n"
                f"Import the attached **`.conf`** file or scan the **QR code** on mobile."
            ),
            "color": 0x10B981,
            "fields": [
                {"name": "Device Name", "value": f"`{peer['deviceName']}`", "inline": True},
                {"name": "Tunnel IP", "value": f"`{peer['assignedIp']}/32`", "inline": True},
                {"name": "Gateway", "value": f"{node.get('flagEmoji', '🌐')} {node['name']}", "inline": True},
                {"name": "Endpoint", "value": f"`{node['publicIp']}:{node['endpointPort']}`", "inline": True},
                {"name": "DNS", "value": f"`{node['dnsServers']}`", "inline": True},
                {"name": "Peer ID", "value": f"`{peer['id']}`", "inline": True},
            ],
            "footer": {
                "text": "Zero-Knowledge Guarantee: Private key was generated locally in memory and never sent to server."
            },
        }

        files = [
            (f"tct-{safe_slug}.conf", conf_text.encode("utf-8"), "text/plain"),
            (f"tct-{safe_slug}-qr.png", qr_bytes, "image/png"),
        ]

        await i.followup(embeds=[embed], files=files, ephemeral=True)
    except Exception as exc:
        await i.followup(f"❌ Tunnel provisioning failed: {exc}", ephemeral=True)


@subcommand(
    "vpn",
    "WireGuard VPN Mesh Control Plane",
    "status",
    "View your active WireGuard tunnels and data transfer statistics",
)
async def vpn_status(i: Interaction):
    await i.defer(ephemeral=True)
    try:
        res = await api_request("GET", f"/peers?discordUserId={i.user_id}")
        peers = res.get("peers", [])
        if not peers:
            return await i.followup(
                "You have no active TCT-VPN tunnels.\nUse `/vpn create region:<name>` to provision your first tunnel!",
                ephemeral=True,
            )

        fields = []
        for p in peers:
            node = p.get("node", {})
            flag = node.get("flagEmoji", "🌐")
            node_name = node.get("name", "Unknown Node")
            rx_mb = round(int(p.get("rxBytes", "0")) / (1024 * 1024), 2)
            tx_mb = round(int(p.get("txBytes", "0")) / (1024 * 1024), 2)
            handshake = p.get("lastHandshake") or "No handshake yet"

            fields.append({
                "name": f"📱 {p['deviceName']} (`{p['id']}`)",
                "value": (
                    f"• **Gateway:** {flag} {node_name}\n"
                    f"• **Assigned IP:** `{p['assignedIp']}`\n"
                    f"• **Traffic:** ⬇️ `{rx_mb} MB` | ⬆️ `{tx_mb} MB`\n"
                    f"• **Last Handshake:** `{handshake}`"
                ),
                "inline": False,
            })

        embed = {
            "title": "🛡️ Your Active TCT-VPN Profiles",
            "description": f"You currently have **{len(peers)}/5** active WireGuard tunnels.",
            "color": 0x10B981,
            "fields": fields,
            "footer": {"text": "To revoke a tunnel, run /vpn revoke peer_id:<id>"},
        }

        await i.followup(embeds=[embed], ephemeral=True)
    except Exception as exc:
        await i.followup(f"❌ Failed to fetch VPN status: {exc}", ephemeral=True)


