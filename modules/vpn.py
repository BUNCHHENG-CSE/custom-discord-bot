from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey

from config import Config
from interactions import Interaction, STR, subcommand

log = logging.getLogger("modules.vpn")


def generate_wireguard_keypair() -> tuple[str, str]:
    """Generate Curve25519 keypair in memory. Private key never leaves the bot process."""
    private_key = X25519PrivateKey.generate()
    public_key = private_key.public_key()

    priv_bytes = private_key.private_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PrivateFormat.Raw,
        encryption_algorithm=serialization.NoEncryption(),
    )
    pub_bytes = public_key.public_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PublicFormat.Raw,
    )

    priv_b64 = base64.b64encode(priv_bytes).decode("ascii")
    pub_b64 = base64.b64encode(pub_bytes).decode("ascii")
    return priv_b64, pub_b64


def build_wireguard_conf(
    *,
    device_name: str,
    node_name: str,
    client_private_key: str,
    assigned_ip: str,
    dns_servers: str,
    server_public_key: str,
    endpoint_ip: str,
    endpoint_port: int,
    preshared_key: str | None = None,
) -> str:
    psk_line = f"PresharedKey = {preshared_key}\n" if preshared_key else ""
    clean_ip = assigned_ip.split("/")[0]
    return (
        f"# Generated by TCT-VPN Discord Bot\n"
        f"# Device: {device_name} | Region: {node_name}\n"
        f"[Interface]\n"
        f"PrivateKey = {client_private_key}\n"
        f"Address = {clean_ip}/32\n"
        f"DNS = {dns_servers}\n\n"
        f"[Peer]\n"
        f"PublicKey = {server_public_key}\n"
        f"{psk_line}"
        f"AllowedIPs = 0.0.0.0/0, ::/0\n"
        f"Endpoint = {endpoint_ip}:{endpoint_port}\n"
        f"PersistentKeepalive = 25\n"
    )


def render_qr_png(conf_text: str) -> bytes:
    qr = qrcode.QRCode(
        version=None,
        error_correction=qrcode.constants.ERROR_CORRECT_M,
        box_size=8,
        border=2,
    )
    qr.add_data(conf_text)
    qr.make(fit=True)
    img = qr.make_image(fill_color="black", back_color="white")
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


async def api_request(
    method: str, path: str, payload: dict[str, Any] | None = None
) -> dict[str, Any]:
    url = f"{Config.TCT_CONTROL_PLANE_API_URL}{path}"
    headers = {
        "x-tct-discord-secret": Config.TCT_DISCORD_API_SECRET,
        "Content-Type": "application/json",
    }
    timeout = aiohttp.ClientTimeout(total=15)
    async with aiohttp.ClientSession(timeout=timeout, headers=headers) as session:
        async with session.request(method, url, json=payload) as resp:
            try:
                data = await resp.json()
            except Exception:
                data = {}
            if resp.status >= 400:
                err_msg = data.get("error") or data.get("message") or f"HTTP {resp.status}"
                raise RuntimeError(err_msg)
            return data


